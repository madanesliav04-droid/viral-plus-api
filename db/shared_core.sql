create table if not exists public.media_assets (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  module text not null default 'shared' check (module in ('shared','viralplus','editplus')),
  kind text not null default 'source' check (kind in ('source','render','broll','thumbnail','audio')),
  storage_bucket text not null default 'viralplus-videos',
  storage_path text not null,
  original_name text,
  mime_type text not null,
  size_bytes bigint not null check (size_bytes > 0),
  duration_ms integer check (duration_ms is null or duration_ms >= 0),
  width integer check (width is null or width > 0),
  height integer check (height is null or height > 0),
  sha256 text check (sha256 is null or sha256 ~ '^[0-9a-f]{64}$'),
  status text not null default 'uploaded' check (status in ('uploading','uploaded','processing','ready','failed','deleted')),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  deleted_at timestamptz,
  unique (storage_bucket, storage_path),
  check (split_part(storage_path,'/',1) = user_id::text)
);
create index if not exists media_assets_user_created_idx on public.media_assets(user_id, created_at desc);
create index if not exists media_assets_sha_idx on public.media_assets(user_id, sha256) where sha256 is not null;
alter table public.media_assets enable row level security;
create policy media_assets_select_own on public.media_assets for select to authenticated using ((select auth.uid()) = user_id);
revoke all on public.media_assets from anon;
grant select on public.media_assets to authenticated;

