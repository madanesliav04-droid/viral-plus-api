create or replace function public.claim_processing_job(p_worker_id text)
returns setof public.processing_jobs
language plpgsql
security definer
set search_path = public
as $$
begin
  return query
  with candidate as (
    select id
    from public.processing_jobs
    where next_attempt_at <= now()
      and (
        status='queued'
        or (status='failed' and retry_count < max_retries)
        or (
          status in ('processing','transcribing','analyzing','generating_report','planning','rendering','encoding')
          and heartbeat_at < now() - interval '10 minutes'
        )
      )
    order by priority asc, created_at asc
    for update skip locked
    limit 1
  )
  update public.processing_jobs j
  set status='processing',
      progress=greatest(j.progress,1),
      stage='claimed',
      locked_at=now(),
      locked_by=p_worker_id,
      heartbeat_at=now(),
      started_at=coalesce(j.started_at,now()),
      error_code=null,
      error=null,
      updated_at=now()
  from candidate
  where j.id=candidate.id
  returning j.*;
end;
$$;
revoke all on function public.claim_processing_job(text) from public, anon, authenticated;
grant execute on function public.claim_processing_job(text) to service_role;

create or replace function public.refund_job_credit(p_job_id uuid)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  j public.processing_jobs%rowtype;
begin
  select * into j from public.processing_jobs where id=p_job_id for update;
  if not found or not j.credit_consumed or j.credit_refunded_at is not null then return false; end if;

  update public.viralplus_profiles
  set analyses_used=greatest(analyses_used-1,0), updated_at=now()
  where user_id=j.user_id;

  update public.processing_jobs
  set credit_refunded_at=now(), updated_at=now()
  where id=p_job_id;

  return true;
end;
$$;
revoke all on function public.refund_job_credit(uuid) from public, anon, authenticated;
grant execute on function public.refund_job_credit(uuid) to service_role;
